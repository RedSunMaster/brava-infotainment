import { app, ipcMain } from "electron";
import { copyFile, mkdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Each driver's trip history (for the smooth-driving score, challenges, streaks and ghost racing): one file per profile in
 * the app's data folder. Like the explored map, losing it would lose months of driving, so a file that cannot be read is
 * reported as an error (never as "no trips yet", which would let an empty list be saved over it), and the previous save is
 * kept beside it.
 */
const folder = () => path.join(app.getPath("userData"), "drives");
// Profile ids are generated by the app (letters and digits); anything else is refused rather than used in a path.
const fileFor = (id: unknown): string | null => typeof id === "string" && /^[a-z0-9_-]{1,40}$/i.test(id) ? path.join(folder(), `${id}.json`) : null;
// Saves of the same file wait for each other, so a slow write never lands after a newer one.
const queues = new Map<string, Promise<void>>();
const PREVIOUS_EVERY_MS = 10 * 60 * 1000;
const lastPrevious = new Map<string, number>();

export type DrivesLoad = { status: "ok"; data: unknown } | { status: "missing" } | { status: "error"; message: string };

export function registerDrivesIpc(): void {
	ipcMain.handle("drives:load", async (_event, id: unknown): Promise<DrivesLoad> => {
		const file = fileFor(id);
		if (!file) return { status: "error", message: "bad profile id" };
		await queues.get(file);
		let text: string;
		try { text = await readFile(file, "utf8"); } catch (cause) {
			if ((cause as NodeJS.ErrnoException).code === "ENOENT") return { status: "missing" };
			return { status: "error", message: String(cause) };
		}
		try { return { status: "ok", data: JSON.parse(text) as unknown }; } catch (cause) {
			await copyFile(file, `${file}.damaged-${Date.now()}`).catch((): void => undefined);
			return { status: "error", message: String(cause) };
		}
	});
	ipcMain.handle("drives:save", (_event, id: unknown, data: unknown) => {
		const file = fileFor(id);
		if (!file || typeof data !== "string") return false;
		const write = async () => {
			await mkdir(folder(), { recursive: true });
			if (Date.now() - (lastPrevious.get(file) ?? 0) > PREVIOUS_EVERY_MS) {
				const previous = await readFile(file, "utf8").catch((): null => null);
				if (previous !== null) { await writeFile(`${file}.previous`, previous, "utf8"); lastPrevious.set(file, Date.now()); }
			}
			// Written beside the real file and then swapped in, so a power cut mid-write never loses the history.
			const temp = `${file}.tmp`;
			await writeFile(temp, data, "utf8");
			await rename(temp, file);
		};
		const next = (queues.get(file) ?? Promise.resolve()).then(write, write).catch((cause: unknown) => console.error("Trip history not saved:", cause));
		queues.set(file, next);
		return next.then(() => true);
	});
	ipcMain.handle("drives:delete", async (_event, id: unknown) => {
		const file = fileFor(id);
		if (!file) return false;
		await queues.get(file);
		try { await unlink(file); } catch { /* Nothing saved yet. */ }
		return true;
	});
}
