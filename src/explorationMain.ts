import { app, ipcMain } from "electron";
import { copyFile, mkdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Explore mode's map of where each driver has been. It can grow to a few megabytes, more than the renderer's local
 * storage should hold, so it lives in one file per profile in the app's data folder.
 *
 * Losing it would lose months of driving, so: a save that cannot be read is reported as an error (never as "no map
 * yet", which would let a fresh empty map be saved over it); the previous save is kept beside it; and a save that
 * would shrink the map by more than half (other than clearing it on purpose) keeps a dated copy of the old one first.
 */
const folder = () => path.join(app.getPath("userData"), "exploration");
// Profile ids are generated by the app (letters and digits); anything else is refused rather than used in a path.
const fileFor = (id: unknown): string | null => typeof id === "string" && /^[a-z0-9_-]{1,40}$/i.test(id) ? path.join(folder(), `${id}.json`) : null;
// Saves of the same file wait for each other, so a slow write never lands after a newer one.
const queues = new Map<string, Promise<void>>();
// The rolling copy of the previous save is refreshed at most this often, to spare the car's storage.
const PREVIOUS_EVERY_MS = 10 * 60 * 1000;
const lastPrevious = new Map<string, number>();

/**
 * Suburb outlines come from OpenStreetMap's Nominatim. Its usage policy asks for at most one request a second and for
 * the app to identify itself, which only the main process can do (browsers will not set a User-Agent).
 */
const NOMINATIM = "https://nominatim.openstreetmap.org/reverse";
const NOMINATIM_GAP_MS = 1_100;
let nominatimQueue: Promise<unknown> = Promise.resolve();

export type ExplorationLoad = { status: "ok"; data: unknown } | { status: "missing" } | { status: "error"; message: string };

/** How many explored cells a saved map holds (its cell list is stored as gaps between cells, one entry per cell). */
function cellCount(text: string): number {
	try {
		const cells = (JSON.parse(text) as { cells?: unknown }).cells;
		return Array.isArray(cells) ? cells.length : 0;
	} catch { return 0; }
}

export function registerExplorationIpc(): void {
	ipcMain.handle("exploration:load", async (_event, id: unknown): Promise<ExplorationLoad> => {
		const file = fileFor(id);
		if (!file) return { status: "error", message: "bad profile id" };
		await queues.get(file);
		let text: string;
		try { text = await readFile(file, "utf8"); } catch (cause) {
			if ((cause as NodeJS.ErrnoException).code === "ENOENT") return { status: "missing" };
			return { status: "error", message: String(cause) };
		}
		try { return { status: "ok", data: JSON.parse(text) as unknown }; } catch (cause) {
			// A damaged file is kept aside for recovery; the renderer is told it could not be read.
			await copyFile(file, `${file}.damaged-${Date.now()}`).catch((): void => undefined);
			return { status: "error", message: String(cause) };
		}
	});
	ipcMain.handle("exploration:save", (_event, id: unknown, data: unknown, cleared?: unknown) => {
		const file = fileFor(id);
		if (!file || typeof data !== "string") return false;
		const write = async () => {
			await mkdir(folder(), { recursive: true });
			const previous = await readFile(file, "utf8").catch((): null => null);
			if (previous !== null) {
				const before = cellCount(previous), after = cellCount(data);
				// A map that suddenly loses more than half of itself, without being cleared on purpose, keeps a dated copy.
				if (cleared !== true && before > 20 && after < before / 2) {
					await writeFile(`${file}.before-shrink-${Date.now()}`, previous, "utf8");
					console.warn(`Explore map for ${String(id)} shrank from ${before} to ${after} cells; kept a copy of the old one.`);
				}
				if (Date.now() - (lastPrevious.get(file) ?? 0) > PREVIOUS_EVERY_MS) {
					await writeFile(`${file}.previous`, previous, "utf8");
					lastPrevious.set(file, Date.now());
				}
			}
			// Written beside the real file and then swapped in, so a power cut mid-write never loses the whole map.
			const temp = `${file}.tmp`;
			await writeFile(temp, data, "utf8");
			await rename(temp, file);
		};
		const next = (queues.get(file) ?? Promise.resolve()).then(write, write).catch((cause: unknown) => console.error("Explore map not saved:", cause));
		queues.set(file, next);
		return next.then(() => true);
	});
	// The suburb at a point, with its outline (Nominatim's JSON), or null if the lookup failed.
	ipcMain.handle("exploration:suburb-at", (_event, lng: unknown, lat: unknown) => {
		if (typeof lng !== "number" || typeof lat !== "number" || !Number.isFinite(lng) || !Number.isFinite(lat)) return null;
		const params = new URLSearchParams({ lat: lat.toFixed(5), lon: lng.toFixed(5), zoom: "14", format: "jsonv2", polygon_geojson: "1", polygon_threshold: "0.0001" });
		const run = async (): Promise<unknown> => {
			try {
				const response = await fetch(`${NOMINATIM}?${params}`, { headers: { "User-Agent": `brava-infotainment/${app.getVersion()}`, "Accept-Language": "en" }, signal: AbortSignal.timeout(10_000) });
				return response.ok ? await response.json() as unknown : null;
			} catch { return null; }
		};
		const result = nominatimQueue.then(run, run);
		// The next lookup waits a little over a second after this one.
		nominatimQueue = result.then(() => new Promise(resolve => setTimeout(resolve, NOMINATIM_GAP_MS)));
		return result;
	});
	ipcMain.handle("exploration:delete", async (_event, id: unknown) => {
		const file = fileFor(id);
		if (!file) return false;
		await queues.get(file);
		try { await unlink(file); } catch { /* Nothing saved yet. */ }
		return true;
	});
}
