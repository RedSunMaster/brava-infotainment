// Builds every picture of the Brava start-up from the Matrice pack (Design/Brava-Matrice, made by its source/make_matrice.py), so the
// boot animation, the early desktop splash and the app's opening screen all end on the same picture.
//   deploy/boot/plymouth/portrait-0001..0062.png   Plymouth animation for an upright screen (1080x1920, transparent)
//   deploy/boot/plymouth/landscape-0001..0062.png  the same turned a quarter turn clockwise, for the panel's raw landscape framebuffer
//                                                  (frame 62 is the held end; the pack's frames 62-72 are all identical to it)
//   deploy/boot/brand/matrice-portrait.png         the held end on its own (transparent), kept as the brand master
//   deploy/boot/splash.png                         the early desktop splash: the held end on the background colour
//   src/assets/boot/matrice-loop.webm              the app's opening-screen loop (transparent; first and last frame = the held end)
//   src/index.html                                 the app's opening screen (between the brand markers), the held end inlined
// All are full-canvas pictures: show them centred, never rescaled by a "logo size" rule.
// Run: node tools/make-brand.mjs [path to the Brava-Matrice pack]
import sharp from "sharp";
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import assert from "node:assert/strict";

export const BACKGROUND = "#0a0705";
export const FRAMES = 62;
const PACK = process.argv[2] ?? "../../Design/Brava-Matrice";
const flat = (file) => sharp(file).flatten({ background: BACKGROUND }).png({ compressionLevel: 9 });
const pad = (n) => String(n).padStart(4, "0");

if (process.argv[1] && process.argv[1].endsWith("make-brand.mjs")) {
	const held = join(PACK, "held-end.png");
	const meta = await sharp(held).metadata();
	assert.equal(`${meta.width}x${meta.height}`, "1080x1920", "the Matrice held end should be 1080x1920");

	// Plymouth: clear out old pictures, then the two frame sets.
	const ply = "deploy/boot/plymouth";
	for (const name of await readdir(ply)) if (name.endsWith(".png")) await rm(join(ply, name));
	for (let i = 1; i <= FRAMES; i++) {
		await copyFile(join(PACK, "boot", `frame-${pad(i)}.png`), join(ply, `portrait-${pad(i)}.png`));
		await copyFile(join(PACK, "boot-clockwise", `frame-${pad(i)}.png`), join(ply, `landscape-${pad(i)}.png`));
	}
	const last = await readFile(join(ply, `portrait-${pad(FRAMES)}.png`));
	assert.ok(last.equals(await readFile(held)), `frame ${FRAMES} should be the held end`);

	// Brand master and the early desktop splash.
	for (const old of await readdir("deploy/boot/brand")) await rm(join("deploy/boot/brand", old));
	await copyFile(held, "deploy/boot/brand/matrice-portrait.png");
	await flat(held).toFile("deploy/boot/splash.png");

	// The app's loop video.
	await mkdir("src/assets/boot", { recursive: true });
	await copyFile(join(PACK, "app-loop.webm"), "src/assets/boot/matrice-loop.webm");

	// The app's opening screen: pure HTML with the picture inlined, so it paints before any script has loaded.
	const data = (await flat(held).toBuffer()).toString("base64");
	const block = `<!-- brand:start (generated by tools/make-brand.mjs) -->
		<div id="splash" aria-hidden="true"><img id="splash-logo" alt="" src="data:image/png;base64,${data}" /></div>
		<!-- brand:end -->`;
	let html = await readFile("src/index.html", "utf8");
	const crlf = html.includes("\r\n");
	html = html.replace(/\r\n/g, "\n");
	html = html.replace(/<!-- brand:start[\s\S]*?brand:end -->/, () => block);
	html = html.replace(/#060a14|#0a0705/g, BACKGROUND);
	if (crlf) html = html.replace(/\n/g, "\r\n");
	await writeFile("src/index.html", html);
	console.log(`written: ${FRAMES} portrait + ${FRAMES} landscape Plymouth frames, deploy/boot/splash.png, src/assets/boot/matrice-loop.webm, src/index.html splash`);
}
