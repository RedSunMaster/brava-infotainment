// Builds every picture of the Brava start-up from the Traccia stills (deploy/boot/brand, from Brava-Traccia.zip: held-end.png and
// held-end-clockwise.png), so the boot splash and the app's opening screen are the same picture. Stills only, no animation.
//   deploy/boot/plymouth/splash-portrait.png   Plymouth, for an upright screen
//   deploy/boot/plymouth/splash-landscape.png  Plymouth, for the panel's raw landscape framebuffer (the quarter-turned picture)
//   deploy/boot/splash.png                     the early desktop splash (upright)
//   src/index.html                             the app's opening screen (between the brand markers), the picture inlined
// All are full-canvas pictures flattened onto the background colour: show them centred, never rescaled by a "logo size" rule.
// Run: node tools/make-brand.mjs
import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";

export const BACKGROUND = "#060a14";
const flat = (file) => sharp(file).flatten({ background: BACKGROUND }).png({ compressionLevel: 9 });

if (process.argv[1] && process.argv[1].endsWith("make-brand.mjs")) {
	await flat("deploy/boot/brand/traccia-portrait.png").toFile("deploy/boot/plymouth/splash-portrait.png");
	await flat("deploy/boot/brand/traccia-landscape.png").toFile("deploy/boot/plymouth/splash-landscape.png");
	await flat("deploy/boot/brand/traccia-portrait.png").toFile("deploy/boot/splash.png");

	// The app's opening screen: pure HTML with the picture inlined, so it paints before any script has loaded.
	const data = (await flat("deploy/boot/brand/traccia-portrait.png").toBuffer()).toString("base64");
	const block = `<!-- brand:start (generated by tools/make-brand.mjs) -->
		<div id="splash" aria-hidden="true"><img id="splash-logo" alt="" src="data:image/png;base64,${data}" /></div>
		<!-- brand:end -->`;
	let html = await readFile("src/index.html", "utf8");
	const crlf = html.includes("\r\n");
	html = html.replace(/\r\n/g, "\n");
	html = html.replace(/<!-- brand:start[\s\S]*?brand:end -->/, () => block);
	if (crlf) html = html.replace(/\n/g, "\r\n");
	await writeFile("src/index.html", html);
	console.log("written: plymouth splash-portrait/landscape.png, deploy/boot/splash.png, src/index.html splash");
}
