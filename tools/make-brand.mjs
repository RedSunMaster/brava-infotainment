// Draws the Brava start-up logo and writes everything that shows it, so the boot splash and the app's opening screen are the same picture:
//   deploy/boot/plymouth/logo.png, glow.png   the Plymouth boot splash theme's images (the same canvas, so they line up)
//   deploy/boot/splash.png                    the same picture in one piece, for the early desktop splash
//   src/index.html                            the app's opening screen (between the brand markers)
// Run: node tools/make-brand.mjs
import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";

export const BACKGROUND = "#060a14";
/** The canvas: the lettering sits in the middle with room for the glow. Every picture of the logo uses this same box. */
export const VIEWBOX = "-80 -100 558 248";
const [VX, VY, VW, VH] = VIEWBOX.split(" ").map(Number);

// Lettering drawn as strokes with round ends: BRAVA large, FIAT small above it, with a thin rule.
const BIG = "M0 0V100M0 0H34A23 23 0 0 1 34 46H0M34 46H40A27 27 0 0 1 40 100H0";
const letters = {
	B: BIG,
	R: "M0 100V0H34A23 23 0 0 1 34 46H0M30 46L58 100",
	A: "M0 100L31 0L62 100M12 66H50",
	V: "M0 0L31 100L62 0",
};
const word = [..."BRAVA"].map((ch, i) => `<path transform="translate(${i * 84} 0)" d="${letters[ch]}"/>`).join("");
const small = { F: "M0 26V0H16M0 13H13", I: "M0 0V26", A: "M0 26L9 0L18 26M3 17H15", T: "M0 0H18M9 0V26" };
const fiatX = [0, 30, 44, 76];
const fiat = [..."FIAT"].map((ch, i) => `<path transform="translate(${fiatX[i]} -54)" d="${small[ch]}"/>`).join("");

const lettering = (colour, width, extra = "") =>
	`<g fill="none" stroke="${colour}" stroke-linecap="round" stroke-linejoin="round" ${extra}><g stroke-width="${width}">${word}</g><g stroke-width="5" opacity="0.7">${fiat}<path d="M118 -41H398"/></g></g>`;

/** The logo as an SVG. `glow` adds the soft blue light behind the letters; `id` keeps filter names apart when it is inlined in a page. */
export function logoSvg({ glow = true, id = "b", attributes = "" } = {}) {
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}" ${attributes}>
${glow ? `<defs><filter id="${id}-glow" x="-30%" y="-60%" width="160%" height="220%"><feGaussianBlur stdDeviation="14"/></filter></defs>
<g filter="url(#${id}-glow)" opacity="0.42">${lettering("#5aa9ff", 20)}</g>` : ""}
${lettering("#f3f7ff", 12)}</svg>`;
}

const scale = 3;
const png = async (svg, file) => sharp(Buffer.from(svg), { density: 72 * scale }).resize(VW * scale, VH * scale).png().toFile(file);

if (process.argv[1] && process.argv[1].endsWith("make-brand.mjs")) {
	// Plymouth wants the letters and the glow as two pictures, so it can place and fade them itself.
	const lettersOnly = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}">${lettering("#f3f7ff", 12)}</svg>`;
	const glowOnly = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}"><defs><filter id="g" x="-30%" y="-60%" width="160%" height="220%"><feGaussianBlur stdDeviation="14"/></filter></defs><g filter="url(#g)" opacity="0.42">${lettering("#5aa9ff", 20)}</g></svg>`;
	await png(lettersOnly, "deploy/boot/plymouth/logo.png");
	await png(glowOnly, "deploy/boot/plymouth/glow.png");
	// The boot framebuffer is the monitor's own landscape shape, and Plymouth's runtime Rotate keeps the old picture size (it cuts the ends
	// off), so the quarter-turned pictures are made here, a quarter turn clockwise, the way the last boot showed upright.
	for (const name of ["logo", "glow"]) await sharp(`deploy/boot/plymouth/${name}.png`).rotate(90).toFile(`deploy/boot/plymouth/${name}-turned.png`);
	// The early desktop splash draws both together as one picture (letters over glow, on a transparent canvas).
	await png(logoSvg({ id: "e" }), "deploy/boot/splash.png");

	// The app's opening screen: pure HTML and an inline SVG, so it paints before any script has loaded.
	const block = `<!-- brand:start (generated by tools/make-brand.mjs) -->
		<div id="splash" aria-hidden="true">${logoSvg({ id: "s", attributes: 'id="splash-logo"' }).replace(/\n/g, "")}</div>
		<!-- brand:end -->`;
	let html = await readFile("src/index.html", "utf8");
	const crlf = html.includes("\r\n");
	html = html.replace(/\r\n/g, "\n");
	html = /<!-- brand:start[\s\S]*?brand:end -->/.test(html) ? html.replace(/<!-- brand:start[\s\S]*?brand:end -->/, block) : html.replace('<div id="root"></div>', `<div id="root"></div>\n\t\t${block}`);
	if (crlf) html = html.replace(/\n/g, "\r\n");
	await writeFile("src/index.html", html);
	console.log("written: plymouth logo.png + glow.png, src/index.html splash");
}
